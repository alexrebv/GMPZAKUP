/** Ответ каждой схемы ключа словами: «api-key — 404, Authorization: Bearer — 401». */
const поСхемам = (с) => СХЕМЫ_КЛЮЧА.map((имя, i) => `${имя} — ${с[i] || 'без HTTP-ответа'}`).join(', ');

/**
 * Текст ошибки заказов FBO. Различает три случая, и ответ шлюза в каждом
 * остаётся в тексте — по его телу видно, что именно шлюз сказал:
 *   OPERATION_NOT_SUPPORTED — FBO кабинету не подключён;
 *   404 на обеих схемах ключа — метода на этом адресе нет;
 *   схемы ответили по-разному (404 и 401, 404 и 400) — это НЕ «метода нет»:
 *     текст начинается с ответа каждой схемы, а не с «HTTP 404».
 */
export function ошибкаЗаказовFbo(е, хост) {
  const ответ = `. Ответ шлюза: ${е.message}`;
  if (неПодключено(е)) {
    return new Error('М.Видео: FBO для этого кабинета не подключён — шлюз ответил '
      + `OPERATION_NOT_SUPPORTED на /v1/order/fbo/list [${хост}]${ответ}`);
  }
  const с = е.статусы;
  if (с && с[0] === 404 && с[1] === 404) {
    return new Error(`М.Видео: на шлюзе ${хост} нет метода /v1/order/fbo/list ни с одной схемой `
      + `ключа (${поСхемам(с)}) — FBO-заказы этим адресом не отдаются${ответ}`);
  }
  if (с) {
    return new Error(`М.Видео: /v1/order/fbo/list на шлюзе ${хост} не отдал заказы ни с одной `
      + `схемой ключа: ${поСхемам(с)}${ответ}`);
  }
  if (статусОшибки(е) === 404) {
    return new Error(`М.Видео: на шлюзе ${хост} нет метода /v1/order/fbo/list (HTTP 404) `
      + `— FBO-заказы этим адресом не отдаются${ответ}`);
  }
  return е;
}

/**
 * Адрес шлюза ещё не подтверждён — подтвердить его методом, который на шлюзе
 * М.Видео заведомо есть. Нужно перед методом, которого на шлюзе может не быть:
 * его 404 первым запросом процесса увёл бы ВСЕ задачи М.Видео на запасной
 * api.omniom.ru до перезапуска воркера (см. №50 в передаче кода).
 */
export async function подтвердитьАдрес(вызов = мв) {
  if (адресПроверен) return;
  await мвОбход('/v1/merchant/location/list', 'locations', {}, вызов);
}

/**
 * Заказы FBO — то, что площадка ведёт со своего склада.
 * Фильтр по дате ИЗМЕНЕНИЯ, как у FBS: смена статуса у старого заказа сама
 * попадает в окно.
 */
export async function мвЗаказыFbo(задача) {
  const { с, по } = период(задача);
  await подтвердитьАдрес();
  let заказы;
  try {
    заказы = await мвОбход('/v1/order/fbo/list', 'orders',
      { updated_since: сСмещением(с), updated_to: сСмещением(по) });
  } catch (е) {
    throw ошибкаЗаказовFbo(е, текущийАдрес());
  }
  const отметка = вТаблицу(new Date());
  const строки = заказы.map((з) => мвСтрокаЗаказаFbo(з, отметка));
  const итог = await сохранить('Заказы Мвидео FBO', строки);
  return `заказов FBO ${заказы.length}, новых ${итог.новых}, изменено ${итог.изменено}`
       + `${итог.заметка}${пометкаАдреса()}${пометкаСхемы('/v1/order/fbo/list')}`;
}

/** Соответствия «артикул продавца ↔ ID товара» для каталога. */
export async function мвТовары() {
  return (await мвОбход('/v1/product/mapping/list', 'mappings'))
    .map((м) => ({ артикул: String(м.offer_id ?? '').trim(), ид: String(м.product_id ?? '').trim(),
      архив: м.is_archived === true }))
    .filter((м) => м.артикул);
}
