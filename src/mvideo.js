import { сохранить } from './sheets.js';
import { требовать } from './config.js';
import { запрос, сон, вТаблицу, число, период, текстом, строгоТекстом,
  сСмещением } from './http.js';

/* ══════════════════ М.ВИДЕО (omninet) ══════════════════
 * Открытый API продавца М.Видео по стандарту omninet (спецификация —
 * omni-net.dev/spec, эталонный клиент — github.com/open-commerce-foundation/sdk-go).
 * Все методы — POST с JSON, листаются курсором: в первом запросе курсор null,
 * дальше — `next_cursor` из ответа.
 *
 * Ключ М.Видео уходит только заголовком `api-key` (так требует спецификация
 * omni-net.sellers.mvideo.ru/api-docs). `Authorization: Bearer` — только для
 * запасного адреса api.omniom.ru: на боевом шлюзе М.Видео лишний заголовок
 * авторизации ломал запрос. Адресов два: первый, который ответил не 404/401
 * и не сетевой ошибкой, запоминается до конца работы. MVIDEO_API_URL, если
 * задан, — единственный адрес.
 *
 * Первая страница списка. В спецификации у курсора и лимита нет ни границ,
 * ни обязательности, а шлюз на неподходящее тело отвечает голым «HTTP 400
 * Некорректный запрос». Поэтому первая страница пробуется в трёх видах — с
 * пустым курсором, без курсора, без курсора и лимита; вид, который прошёл,
 * запоминается для метода и дальше листается им же.
 *
 * Схем три: FBS и DBS — со своего склада, FBO — со склада площадки. FBO описан
 * в стандарте omninet отдельным справочником (omni-net.dev/spec/api/fbo), хотя в
 * спецификации самого шлюза М.Видео (omni-net.sellers.mvideo.ru/api-docs) его
 * методов не видно. Поэтому FBO здесь не предполагается, а проверяется:
 *
 *   остатки FBO — тот же /v1/product/stock/info, что и у FBS; строки на складе
 *     площадки отличаются тем, что у них есть market_location_id и нет
 *     location_id. Прежний код такие строки, приди они, отбросил бы;
 *   заказы FBO — /v1/order/fbo/list.
 *
 * Проверено в проде 05.11.2026: шлюз М.Видео FBO не отдаёт. /v1/order/fbo/list
 * на omni-net.sellers.mvideo.ru отвечает 404, а в остатках все строки — со
 * своего склада, со склада площадки ни одной. Код оставлен: он честно говорит
 * об этом и не трогает листы, а если М.Видео FBO включит — заработает сам.
 *
 * Если у кабинета FBO не подключён, стандарт велит шлюзу отвечать
 * «400 OPERATION_NOT_SUPPORTED: операция недоступна для текущей конфигурации».
 * Такой ответ — не ошибка тела запроса, и перебирать виды тела на нём незачем:
 * задача падает с прямым текстом, а лист не трогается.
 *
 * Строка заказа — это одна позиция: `offer_id` и `product_id` у заказа свои,
 * количества в ответе нет. Если продавец уже передал экземпляры, их число и
 * есть количество; до этого — одна штука.
 *
 * Цены приходят целым числом, умноженным на 100.
 */
const АДРЕСА = process.env.MVIDEO_API_URL
  ? [process.env.MVIDEO_API_URL]
  : ['https://omni-net.sellers.mvideo.ru', 'https://api.omniom.ru'];
const ПАЧКА = 100;
const СТРАНИЦ = 2000;

let адрес = 0;
let адресПроверен = АДРЕСА.length === 1;

/** Адрес, на который сейчас ходят запросы. */
export const текущийАдрес = () => АДРЕСА[адрес];

/**
 * Пометка для «Результата», если запросы ушли на запасной адрес.
 *
 * Выбор адреса запоминается на всю жизнь воркера. Если при старте процесса
 * первый запрос к шлюзу М.Видео упал хоть раз, все дальнейшие уходят на
 * api.omniom.ru — другую систему, — и задачи продолжают «успешно» писать
 * в книгу её данные. Без этой пометки этого не видно ни в одной ячейке.
 */
export function пометкаАдреса(номер = адрес, адреса = АДРЕСА) {
  if (!номер) return '';
  return `, ЧЕРЕЗ ЗАПАСНОЙ АДРЕС ${String(адреса[номер]).replace(/^https?:\/\//, '')}`;
}

/** Ответ, после которого стоит попробовать другой адрес: не тот хост или не та авторизация. */
const другойАдрес = (е) => /HTTP 40[14]|fetch failed|ENOTFOUND|EAI_AGAIN|ECONNREFUSED|getaddrinfo/
  .test(String(е?.message || ''));

/** Заголовки под адрес: М.Видео — только `api-key`, omniom — ещё и Bearer. */
export function заголовки(хост, ключ) {
  const з = {
    'Content-Type': 'application/json',
    'api-key': ключ,
    // площадка требует User-Agent у всех запросов
    'User-Agent': 'pereschet-po-razmeram/1.0',
  };
  if (/omniom\./i.test(хост)) з.Authorization = `Bearer ${ключ}`;
  return з;
}

async function мв(путь, тело) {
  const [ключ] = требовать('MVIDEO_API_KEY');
  const опции = {
    method: 'POST',
    body: JSON.stringify(тело),
  };
  const ошибки = [];
  for (;;) {
    опции.headers = заголовки(АДРЕСА[адрес], ключ);
    try {
      const ответ = await запрос(АДРЕСА[адрес] + путь, опции,
        { имя: `М.Видео ${путь}`, пауза: 2000, попыток: адресПроверен ? 5 : 2 });
      адресПроверен = true;
      return ответ;
    } catch (е) {
      if (адресПроверен || !другойАдрес(е) || адрес >= АДРЕСА.length - 1) {
        // с какого адреса пришла ошибка — иначе «404» шлюза М.Видео и «404»
        // запасного api.omniom.ru неотличимы, а значат совершенно разное
        const где = ` [${АДРЕСА[адрес].replace(/^https?:\/\//, '')}]`;
        if (ошибки.length) throw new Error(`${е.message}${где}; до этого: ${ошибки.join('; ')}`);
        е.message = `${е.message}${где}`;
        throw е;
      }
      ошибки.push(`${АДРЕСА[адрес]}: ${String(е.message).slice(0, 120)}`);
      адрес += 1;
    }
  }
}

/** Виды тела первой страницы — от полного к пустому (см. шапку файла). */
export const ВИДЫ = [
  (фильтр) => ({ filter: фильтр, cursor: '', limit: ПАЧКА }),
  (фильтр) => ({ filter: фильтр, limit: ПАЧКА }),
  (фильтр) => ({ filter: фильтр }),
];
/** Какой вид тела прошёл у метода: путь → номер в ВИДЫ. */
const видМетода = new Map();

/** Тело запроса страницы: вид метода, а со второй страницы — ещё и курсор. */
export function телоСтраницы(вид, фильтр, курсор) {
  const тело = ВИДЫ[вид](фильтр);
  if (курсор) тело.cursor = курсор;
  return тело;
}

/** «Операция недоступна для текущей конфигурации» — схема не подключена кабинету. */
export const неПодключено = (е) => /OPERATION_NOT_SUPPORTED/.test(String(е?.message || ''));

/** Первая страница: перебор видов тела по «HTTP 400», пока какой-то не пройдёт. */
async function перваяСтраница(путь, фильтр, вызов = мв) {
  const отказы = [];
  for (let вид = видМетода.get(путь) ?? 0; вид < ВИДЫ.length; вид += 1) {
    try {
      const ответ = await вызов(путь, телоСтраницы(вид, фильтр, ''));
      видМетода.set(путь, вид);
      return { ответ, вид };
    } catch (е) {
      // 400 с OPERATION_NOT_SUPPORTED — про кабинет, а не про тело запроса:
      // другой вид тела его не вылечит, а «тоже 400» отправило бы искать не там
      if (неПодключено(е)) throw е;
      if (!/HTTP 400/.test(String(е?.message || '')) || вид === ВИДЫ.length - 1) {
        if (отказы.length) е.message = `${е.message}; до этого вид тела ${отказы.join(', ')} — тоже 400`;
        throw е;
      }
      отказы.push(вид + 1);
    }
  }
  throw new Error(`М.Видео ${путь}: ни один вид тела не прошёл`);
}

/** Обход по курсору. Курсор, который не двигает выборку, — ошибка, а не круг. */
export async function мвОбход(путь, поле, фильтр = {}, вызов = мв) {
  const итог = [];
  let курсор = '';
  let вид = 0;
  for (let n = 0; n < СТРАНИЦ; n += 1) {
    let ответ;
    if (n === 0) ({ ответ, вид } = await перваяСтраница(путь, фильтр, вызов));
    else ответ = await вызов(путь, телоСтраницы(вид, фильтр, курсор));
    const пачка = ответ?.[поле];
    if (!Array.isArray(пачка)) {
      throw new Error(`М.Видео ${путь}: ответ без списка «${поле}» на странице ${n + 1}`);
    }
    итог.push(...пачка);
    const след = ответ.next_cursor || '';
    if (!след || !пачка.length) return итог;
    if (след === курсор) {
      throw new Error(`М.Видео ${путь}: курсор не двигает выборку на странице ${n + 1}`);
    }
    курсор = след;
    await сон(200);
  }
  throw new Error(`М.Видео ${путь}: прочитано ${итог.length} и упёрлись в предел страниц`);
}

/** Склады продавца: FBS-склады и DBS-локации. Нужны ради имени в колонке «Склад». */
async function склады() {
  const имена = new Map();
  const добавить = (список) => {
    for (const с of список) {
      const ид = String(с.location_id ?? '');
      if (ид) имена.set(ид, с.name || с.merchant_location_id || ид);
    }
  };
  добавить(await мвОбход('/v1/merchant/location/list', 'locations'));
  try {
    добавить(await мвОбход('/v1/location/list', 'locations'));
  } catch (е) {
    // DBS подключён не у всех: без него остаются только FBS-склады
    if (!/HTTP 40[34]/.test(е.message)) throw е;
  }
  return имена;
}

export function мвСтрокаОстатка(о, имена, отметка) {
  const ид = String(о.location_id ?? о.market_location_id ?? '');
  return [текстом(о.offer_id) || '-', имена.get(ид) || ид || '-',
    число(о.available_count ?? о.count), отметка];
}

/** Строка без своего склада, но со складом площадки, — остаток FBO, а не FBS. */
export const наСкладеМП = (о) => !о.location_id && !!о.market_location_id;

const ненулевой = (о) => число(о.available_count) || число(о.count);

/**
 * Ответ /v1/product/stock/info делится на две схемы по тому, чей склад у строки.
 * Нулевые остатки отбрасываются в обеих — как и раньше у FBS.
 */
export function разделитьОстатки(остатки) {
  const fbs = [];
  const fbo = [];
  for (const о of остатки) {
    if (!ненулевой(о)) continue;
    (наСкладеМП(о) ? fbo : fbs).push(о);
  }
  return { fbs, fbo };
}

export async function мвОстаткиFbs() {
  const имена = await склады();
  const отметка = вТаблицу(new Date());
  const { fbs } = разделитьОстатки(await мвОбход('/v1/product/stock/info', 'stocks'));
  const строки = fbs.map((о) => мвСтрокаОстатка(о, имена, отметка));
  await сохранить('FBS остатки Мвидео', строки);
  return `складов ${имена.size}, строк ${строки.length}${пометкаАдреса()}`;
}

/** Из чего состоит ответ остатков — для текста ошибки, когда разобрать его не вышло. */
export function разбивкаОстатков(все) {
  const нулевых = все.filter((о) => !ненулевой(о)).length;
  const наПлощадке = все.filter(наСкладеМП).length;
  const своих = все.filter((о) => !!о.location_id).length;
  const безСклада = все.filter((о) => !о.location_id && !о.market_location_id).length;
  const поля = [...new Set(все.slice(0, 5).flatMap((о) => Object.keys(о || {})))].join(', ');
  return `пришло ${все.length}: нулевых ${нулевых}, на складе площадки ${наПлощадке}, `
       + `на своём складе ${своих}, без склада ${безСклада}; поля строки: ${поля || 'нет'}`;
}

/**
 * Склады площадки: имена для колонки «Склад» в FBO.
 *
 * Без них остаток не теряется — в колонке встанет идентификатор склада. Это
 * снимок: лист переписывается целиком каждый прогон, и имя вернётся при первом
 * же удачном. Поэтому здесь, в отличие от справочника карточек ВБ (№38 каталога),
 * пережить отказ можно — затирать нечего.
 */
async function складыПлощадки(вызов = мв) {
  const имена = new Map();
  try {
    for (const с of await мвОбход('/v1/market/location/list', 'locations', {}, вызов)) {
      const ид = String(с.market_location_id ?? '');
      if (ид) имена.set(ид, с.name || (с.city ? `${с.city}, ${ид}` : ид));
    }
  } catch (е) {
    if (!неПодключено(е) && !/HTTP 40[34]/.test(е.message)) throw е;
  }
  return имена;
}

/** Сбор строк FBO-остатков без записи в книгу: так его проверяет проба. */
export async function мвОстаткиFboСтроки(вызов = мв) {
  const все = await мвОбход('/v1/product/stock/info', 'stocks', {}, вызов);
  const { fbo } = разделитьОстатки(все);
  if (!fbo.length) {
    // снимок с нулём строк сохранить() и так не запишет, но его текст
    // («пришло 0 строк») не объяснил бы, почему: остатки ведь пришли.
    // Прежний текст считал только ненулевые строки своего склада и говорил
    // «со своего склада 0», когда строки просто были нулевыми — это вводило
    // в заблуждение. Теперь разбивка по всему ответу и имена полей строки:
    // по ним видно, не зовётся ли количество или склад иначе, чем ждёт код
    throw new Error(`М.Видео: ненулевых остатков на складах площадки нет — ${разбивкаОстатков(все)}. `
      + 'Лист не перезаписан');
  }
  // склады площадки — после остатков: первым вызовом процесса должен идти метод,
  // который заведомо есть, иначе 404 на нём увёл бы запросы на запасной адрес
  const имена = await складыПлощадки(вызов);
  const отметка = вТаблицу(new Date());
  const строки = fbo.map((о) => мвСтрокаОстатка(о, имена, отметка));
  const безИмени = fbo.filter((о) => !имена.has(String(о.market_location_id))).length;
  const складов = new Set(fbo.map((о) => о.market_location_id)).size;
  return { строки, складов, безИмени };
}

export async function мвОстаткиFbo() {
  const { строки, складов, безИмени } = await мвОстаткиFboСтроки();
  await сохранить('FBO остатки Мвидео', строки);
  return `складов площадки ${складов}, строк ${строки.length}`
       + (безИмени ? `, без имени склада ${безИмени}` : '') + пометкаАдреса();
}

const ЦЕНЫ = ['CUSTOMER_FINAL_PRICE', 'CUSTOMER_PRICE', 'MERCHANT_FINAL_PRICE', 'MERCHANT_PRICE'];

/** Цена покупателя со скидками, если есть; иначе первая, какая пришла. В рублях. */
export function мвЦена(цены = []) {
  for (const тип of ЦЕНЫ) {
    const ц = цены.find((x) => x.price_type === тип);
    if (ц) return число(ц.value) / 100;
  }
  return цены.length ? число(цены[0].value) / 100 : 0;
}

export function мвСтрокаЗаказа(з, схема, отметка) {
  const штук = Array.isArray(з.exemplars) && з.exemplars.length ? з.exemplars.length : 1;
  return [строгоТекстом(з.merchant_order_id || з.client_order_id), вТаблицу(з.created_at),
    текстом(з.offer_id) || '-', штук, мвЦена(з.prices), з.status || '-', схема, отметка];
}

/**
 * Заказы со своего склада: FBS и DBS в один лист.
 *
 * FBS фильтруется по дате ИЗМЕНЕНИЯ — смена статуса у старого заказа сама
 * попадает в окно. DBS метод фильтрует только по дате создания, поэтому его
 * окно должно покрывать цикл доставки, как у Ozon и Яндекса.
 */
export async function мвЗаказыFbs(задача) {
  const { с, по } = период(задача);
  const fbs = await мвОбход('/v1/order/fbs/list', 'orders',
    { updated_since: сСмещением(с), updated_to: сСмещением(по) });
  let dbs = [];
  let заметка = '';
  try {
    dbs = await мвОбход('/v1/order/dbs/list', 'orders',
      { since: сСмещением(с), to: сСмещением(по) });
  } catch (е) {
    // DBS не подключён — это не ошибка FBS-выгрузки, но сказать об этом надо
    if (!/HTTP 40[34]/.test(е.message)) throw е;
    заметка = ', DBS недоступен';
  }
  const отметка = вТаблицу(new Date());
  const строки = [
    ...fbs.map((з) => мвСтрокаЗаказа(з, 'FBS', отметка)),
    ...dbs.map((з) => мвСтрокаЗаказа(з, 'DBS', отметка)),
  ];
  const итог = await сохранить('Заказы Мвидео FBS', строки);
  return `заказов FBS ${fbs.length}, DBS ${dbs.length}${заметка}, `
       + `новых ${итог.новых}, изменено ${итог.изменено}${итог.заметка}${пометкаАдреса()}`;
}

/**
 * Строка заказа FBO. Колонки — как у листа «Заказы Мвидео FBO», без «Схемы».
 * Один заказ в API — один товар; экземпляров у FBO в контракте нет, но если
 * шлюз их пришлёт, считаем по ним — как у FBS.
 */
export function мвСтрокаЗаказаFbo(з, отметка) {
  const штук = Array.isArray(з.exemplars) && з.exemplars.length ? з.exemplars.length : 1;
  return [строгоТекстом(з.merchant_order_id || з.client_order_id), вТаблицу(з.created_at),
    текстом(з.offer_id) || '-', штук, мвЦена(з.prices), з.status || '-', отметка];
}

/**
 * Заказы FBO — то, что площадка ведёт со своего склада.
 * Фильтр по дате ИЗМЕНЕНИЯ, как у FBS: смена статуса у старого заказа сама
 * попадает в окно.
 */
export async function мвЗаказыFbo(задача) {
  const { с, по } = период(задача);
  let заказы;
  try {
    заказы = await мвОбход('/v1/order/fbo/list', 'orders',
      { updated_since: сСмещением(с), updated_to: сСмещением(по) });
  } catch (е) {
    if (неПодключено(е)) {
      throw new Error('М.Видео: FBO для этого кабинета не подключён — шлюз ответил '
        + `OPERATION_NOT_SUPPORTED на /v1/order/fbo/list [${текущийАдрес()}]`);
    }
    if (/HTTP 404/.test(е.message)) {
      throw new Error(`М.Видео: на шлюзе ${текущийАдрес()} нет метода /v1/order/fbo/list `
        + '(HTTP 404) — FBO-заказы этим адресом не отдаются');
    }
    throw е;
  }
  const отметка = вТаблицу(new Date());
  const строки = заказы.map((з) => мвСтрокаЗаказаFbo(з, отметка));
  const итог = await сохранить('Заказы Мвидео FBO', строки);
  return `заказов FBO ${заказы.length}, новых ${итог.новых}, изменено ${итог.изменено}`
       + `${итог.заметка}${пометкаАдреса()}`;
}

/** Соответствия «артикул продавца ↔ ID товара» для каталога. */
export async function мвТовары() {
  return (await мвОбход('/v1/product/mapping/list', 'mappings'))
    .map((м) => ({ артикул: String(м.offer_id ?? '').trim(), ид: String(м.product_id ?? '').trim(),
      архив: м.is_archived === true }))
    .filter((м) => м.артикул);
}
