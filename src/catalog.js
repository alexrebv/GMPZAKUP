/* ══════════════════ КАТАЛОГ ══════════════════
 * Каталог собирается заново из карточек всех площадок: строка — позиция
 * «общий артикул|размер», у позиции все её штрихкоды и артикулы на каждой
 * площадке. Рядом пересобирается лист «Штрихкоды» — по нему формулы книги
 * сводят остатки и заказы ВБ к позициям.
 *
 * Основа — карточки ВБ: артикул продавца и размер. Товары остальных площадок
 * привязываются к позиции по порядку:
 *   1. по любому общему штрихкоду;
 *   2. по тому, к какой позиции этот артикул был привязан в прошлом каталоге;
 *   3. у Ламоды — по артикулу родителя и размеру из номенклатуры;
 *   4. по тому же артикулу на другой площадке (у М.Видео штрихкодов в API нет);
 *   5. по разбору «артикул-размер» с последнего дефиса — тогда же заводится
 *      новая позиция, если такой ещё нет.
 *
 * Чего у площадок нет — группа, бренд и категория у товаров без ВБ, — берётся
 * из прошлого каталога. Площадка без ключей не стирает свои артикулы: они
 * переносятся из прошлого каталога как были, и об этом пишется в «Результат».
 *
 * Главный штрихкод позиции (колонка «Штрихкод»):
 *   * обычный размер — свой код 4620…; если таких несколько или ни одного —
 *     тот, по которому больше продаж; при равенстве — первый;
 *   * размер-вариант («30А», «30.», «30 акция») — первый штрихкод, а если
 *     продажи есть по другому — тот, по которому их больше.
 * Продажи считаются по заказам ВБ из книги: только у ВБ заказы идут со штрихкодом.
 */
const ЛИСТ = 'Каталог';
const МП = ['ВБ', 'ОЗОН', 'Яндекс', 'Ламода', 'Мвидео'];
const ПРЕДЕЛ = 50000;
/** Каталог не может сжаться сильнее этого за один прогон: такое — сбой источника, а не жизнь. */
const ДОЛЯ_ОСТАТЬСЯ = 0.7;

const норм = (х) => String(х ?? '').trim().replace(/^'/, '');
const ключПоз = (арт, разм) => `${норм(арт).toLowerCase()}|${норм(разм).toLowerCase()}`;
const шк = (х) => норм(х).replace(/\.0+$/, '');
const поРусски = (а, б) => а.localeCompare(б, 'ru');

/** Размер-вариант: «30А», «30a», «30а(29)/180», «30.», «30 акция». */
export function вариантРазмера(размер) {
  const р = норм(размер).toLowerCase();
  return /акци/.test(р) || /\d\s*[аa](?![а-яёa-z])/.test(р) || /\d\.(?=\s|$|\()/.test(р);
}

export function главныйШтрихкод(баркоды, размер, продажи = new Map()) {
  if (!баркоды.length) return '';
  const пр = (код) => продажи.get(код) || 0;
  // при равенстве продаж остаётся первый по порядку
  const лучший = (список) => список.reduce((л, код) => (пр(код) > пр(л) ? код : л), список[0]);
  if (вариантРазмера(размер)) return лучший(баркоды);
  const свои = баркоды.filter((код) => код.startsWith('4620'));
  return лучший(свои.length ? свои : баркоды);
}

/** Колонки каталога по заголовкам: лист мог поменять раскладку, имена — нет. */
const ПОЛЯ = {
  баркод: 'Штрихкод', все: 'Все штрихкоды', артикул: 'Общий артикул', размер: 'Размер',
  название: 'Наименование', бренд: 'Бренд', категория: 'Категория', группа: 'Группа',
  ВБ: 'Артикул ВБ', ВБид: 'nmID', ОЗОН: 'Артикул ОЗОН', ОЗОНид: 'SKU ОЗОН',
  Яндекс: 'Артикул Яндекс', Ламода: 'Артикул Ламода', Ламодаид: 'SKU Ламода',
  Мвидео: 'Артикул Мвидео', Мвидеоид: 'ID Мвидео',
};

export function разобратьКаталог(значения) {
  const [шапка = [], ...строки] = значения;
  const где = {};
  for (const [поле, имя] of Object.entries(ПОЛЯ)) где[поле] = шапка.findIndex((з) => норм(з) === имя);
  if (где.артикул < 0 || где.размер < 0) return [];
  const взять = (р, поле) => (где[поле] >= 0 ? норм(р[где[поле]]) : '');
  return строки
    .filter((р) => взять(р, 'артикул'))
    .map((р) => {
      const з = {};
      for (const поле of Object.keys(ПОЛЯ)) з[поле] = взять(р, поле);
      з.баркоды = [з.баркод, ...з.все.split(/[;,\s]+/)].map(шк).filter(Boolean)
        .filter((к, i, м) => м.indexOf(к) === i);
      return з;
    });
}

/**
 * Сборка каталога без обращений к сети: на входе прошлый каталог, товары
 * площадок и продажи по штрихкодам. Вынесено отдельно ради проб.
 */
export function собратьКаталог({ прошлый = [], вб = null, товары = {}, продажи = new Map() }) {
  const позиции = new Map();
  const порядокНовых = [];
  const поШК = new Map();
  const поАртикулу = Object.fromEntries(МП.map((м) => [м, new Map()]));
  const прошлаяПоз = new Map(прошлый.map((п) => [ключПоз(п.артикул, п.размер), п]));
  const прошлыйАртикул = Object.fromEntries(МП.map((м) => [м, new Map()]));
  for (const п of прошлый) {
    for (const м of МП) {
      if (п[м]) прошлыйАртикул[м].set(п[м].toLowerCase(), п);
    }
  }
  const группаАртикула = new Map();
  for (const п of прошлый) {
    const к = п.артикул.toLowerCase();
    if (п.группа && !группаАртикула.has(к)) группаАртикула.set(к, п.группа);
  }
  let дублей = 0;

  const позиция = (арт, разм) => {
    const к = ключПоз(арт, разм);
    if (!позиции.has(к)) {
      // написание — как в прошлом каталоге: «30 АКЦИЯ» не должна стать «30 акция»
      // только потому, что так её завели в карточке, — по позиции сверяются
      // ручные листы книги
      const было = прошлаяПоз.get(к);
      позиции.set(к, { артикул: было?.артикул || норм(арт), размер: было?.размер ?? норм(разм),
        баркоды: [], мп: {}, название: '', бренд: '', категория: '' });
      порядокНовых.push(к);
    }
    return позиции.get(к);
  };
  const добавитьШК = (поз, код) => {
    const к = шк(код);
    if (!к) return;
    const чей = поШК.get(к);
    if (чей && чей !== поз) return; // код уже у другой позиции — не задваиваем
    if (!чей) поШК.set(к, поз);
    if (!поз.баркоды.includes(к)) поз.баркоды.push(к);
  };
  const дополнить = (поз, т) => {
    if (!поз.название && т.название) поз.название = т.название;
    if (!поз.бренд && т.бренд) поз.бренд = т.бренд;
    if (!поз.категория && т.категория) поз.категория = т.категория;
  };
  const привязать = (поз, м, т) => {
    const было = поз.мп[м];
    if (было && было.артикул.toLowerCase() !== т.артикул.toLowerCase()) { дублей += 1; return; }
    if (!было) поз.мп[м] = { артикул: т.артикул, ид: норм(т.ид) };
    поАртикулу[м].set(т.артикул.toLowerCase(), поз);
  };

  // 1. основа — карточки ВБ; без ключа ВБ основа — прошлый каталог
  if (вб) {
    for (const б of вб) {
      if (!норм(б.артикул) || б.артикул === '-') continue;
      const поз = позиция(б.артикул, б.размер);
      добавитьШК(поз, б.баркод);
      привязать(поз, 'ВБ', { артикул: норм(б.артикул), ид: норм(б.nmID) });
      дополнить(поз, { название: б.название, бренд: б.бренд, категория: б.предмет });
    }
  } else {
    for (const п of прошлый.filter((х) => х.ВБ)) {
      const поз = позиция(п.артикул, п.размер);
      п.баркоды.forEach((код) => добавитьШК(поз, код));
      привязать(поз, 'ВБ', { артикул: п.ВБ, ид: п.ВБид });
    }
  }

  const найти = (м, т) => {
    for (const код of т.баркоды || []) {
      const поз = поШК.get(шк(код));
      if (поз) return поз;
    }
    const п = прошлыйАртикул[м].get(т.артикул.toLowerCase());
    if (п) return позиция(п.артикул, п.размер);
    if (т.родитель && т.размер) return позиция(т.родитель, т.размер);
    for (const другая of МП) {
      const поз = поАртикулу[другая].get(т.артикул.toLowerCase());
      if (поз) return поз;
    }
    const разбор = т.артикул.match(/^(.+)-([^-]+)$/);
    return разбор ? позиция(разбор[1], разбор[2]) : позиция(т.артикул, '');
  };

  // 2. остальные площадки; без ключа — их артикулы из прошлого каталога
  for (const м of МП.slice(1)) {
    const список = товары[м];
    if (список) {
      for (const т of список) {
        const поз = найти(м, т);
        (т.баркоды || []).forEach((код) => добавитьШК(поз, код));
        привязать(поз, м, т);
        дополнить(поз, т);
      }
    } else {
      for (const п of прошлый.filter((х) => х[м])) {
        const поз = позиция(п.артикул, п.размер);
        п.баркоды.forEach((код) => добавитьШК(поз, код));
        привязать(поз, м, { артикул: п[м], ид: п[`${м}ид`] || '' });
      }
    }
  }

  // порядок строк — как в прошлом каталоге; новая позиция встаёт за последней
  // позицией своего артикула, а с новым артикулом — в конец
  const порядок = [];
  const видено = new Set();
  for (const п of прошлый) {
    const к = ключПоз(п.артикул, п.размер);
    if (позиции.has(к) && !видено.has(к)) { порядок.push(к); видено.add(к); }
  }
  let новых = 0;
  for (const к of порядокНовых) {
    if (видено.has(к)) continue;
    видено.add(к);
    новых += 1;
    const арт = позиции.get(к).артикул.toLowerCase();
    let i = порядок.length - 1;
    while (i >= 0 && позиции.get(порядок[i]).артикул.toLowerCase() !== арт) i -= 1;
    if (i >= 0) порядок.splice(i + 1, 0, к);
    else порядок.push(к);
  }

  let главных4620 = 0;
  const каталог = [];
  const штрихкоды = [];
  for (const к of порядок) {
    const поз = позиции.get(к);
    const п = прошлаяПоз.get(к) || {};
    const главный = главныйШтрихкод(поз.баркоды, поз.размер, продажи);
    if (главный.startsWith('4620')) главных4620 += 1;
    const все = главный ? [главный, ...поз.баркоды.filter((код) => код !== главный)] : [];
    const группа = п.группа || группаАртикула.get(поз.артикул.toLowerCase()) || '';
    const где = МП.filter((м) => поз.мп[м]).sort(поРусски).join(' + ');
    const мп = (м, поле) => строгоТекстом(поз.мп[м]?.[поле] || '');
    каталог.push([
      строгоТекстом(главный), строгоТекстом(все.join('; ')), все.length,
      строгоТекстом(поз.артикул), строгоТекстом(поз.размер),
      текстом(поз.название || п.название || ''), текстом(поз.бренд || п.бренд || ''),
      текстом(поз.категория || п.категория || ''), строгоТекстом(группа),
      мп('ВБ', 'артикул'), мп('ВБ', 'ид'), мп('ОЗОН', 'артикул'), мп('ОЗОН', 'ид'),
      мп('Яндекс', 'артикул'), мп('Ламода', 'артикул'), мп('Ламода', 'ид'),
      мп('Мвидео', 'артикул'), мп('Мвидео', 'ид'), где,
    ]);
    const имя = `${поз.артикул}|${поз.размер}`;
    for (const код of все) {
      if (поШК.get(код) !== поз) continue;
      штрихкоды.push([строгоТекстом(код), строгоТекстом(поз.артикул), строгоТекстом(поз.размер),
        строгоТекстом(имя)]);
    }
  }
  const ушло = прошлый.length ? [...прошлаяПоз.keys()].filter((к) => !позиции.has(к)).length : 0;
  return { каталог, штрихкоды, новых, ушло, дублей, главных4620 };
}

/**
 * Шапка листа должна совпадать со схемой колонка в колонку. Пустая клетка
 * допустима — её дозаполнит запись, — а чужое имя означает другую раскладку.
 */
export function сверитьШапку(шапка, схема) {
  for (let i = 0; i < схема.length; i += 1) {
    const есть = норм(шапка[i]);
    if (есть && есть !== схема[i]) {
      return `лист «${ЛИСТ}»: в колонке ${String.fromCharCode(65 + i)} «${есть}» вместо `
        + `«${схема[i]}» — раскладка не совпадает со схемой, каталог не записан`;
    }
  }
  return '';
}

/** Продажи по штрихкодам — из заказов ВБ в книге. Лист, которого нет, просто не считается. */
async function продажиПоШтрихкодам() {
  const продажи = new Map();
  for (const диапазон of [`'Заказы ВБ FBO'!E2:E${ПРЕДЕЛ}`, `'Заказы ВБ FBS'!D2:D${ПРЕДЕЛ}`,
    `'WB заказы проверка'!G2:G${ПРЕДЕЛ}`]) {
    let значения = [];
    try { значения = await читать(диапазон); } catch { continue; }
    for (const [з] of значения) {
      const код = шк(з);
      if (код) продажи.set(код, (продажи.get(код) || 0) + 1);
    }
  }
  return продажи;
}

/**
 * Площадка без ключей пропускается — её артикулы переедут из прошлого каталога.
 * `необязательна`: сбой площадки не валит каталог — её артикулы так же берутся
 * из прошлого каталога, а ошибка видна в «Статусе». ОЗОН и Яндекс обязательны:
 * их сбой — ошибка прохода и повтор через «Каждые, мин».
 */
export const ИСТОЧНИКИ = {
  ОЗОН: { ключи: ['OZON_CLIENT_ID', 'OZON_API_KEY'], загрузить: ozonТовары },
  Яндекс: { ключи: ['YM_API_KEY'], загрузить: ямТовары },
  Ламода: { ключи: ['LAMODA_CLIENT_ID', 'LAMODA_CLIENT_SECRET'], загрузить: лмТовары, необязательна: true },
  Мвидео: { ключи: ['MVIDEO_API_KEY'], загрузить: мвТовары, необязательна: true },
};

/** Товары всех площадок. Возвращает и то, что пропущено, — с причиной. */
export async function товарыПлощадок(источники = ИСТОЧНИКИ, есть = доступ) {
  const товары = {};
  const пропущены = [];
  for (const [м, и] of Object.entries(источники)) {
    if (!и.ключи.every(есть)) { пропущены.push(м); continue; }
    try {
      const список = await и.загрузить();
      if (!список.length) throw new Error(`${м}: пришло 0 товаров — каталог не перезаписан`);
      товары[м] = список;
    } catch (е) {
      const текст = String(е?.message || е);
      // ключ есть, но настройки неполные (нет кампании, нет sellerId) — тот же пропуск
      if (текст.startsWith('не заполнено')) {
        пропущены.push(`${м} (${текст.replace('не заполнено: ', 'нет ')})`);
      } else if (и.необязательна) {
        пропущены.push(`${м} (сбой: ${текст.slice(0, 160)})`);
      } else {
        throw е;
      }
    }
  }
  return { товары, пропущены };
}

export async function каталог() {
  const ширина = СХЕМЫ[ЛИСТ].length;
  const значения = await читать(`'${ЛИСТ}'!A1:AF${ПРЕДЕЛ}`);
  // правее схемы на листе формулы книги: при чужой раскладке запись легла бы
  // поверх «Позиции», поэтому сначала сверяем шапку
  const расхождение = сверитьШапку(значения[0] || [], СХЕМЫ[ЛИСТ]);
  if (расхождение) throw new Error(расхождение);
  const прошлый = разобратьКаталог(значения);
  const пропущены = [];
  const вб = доступ('WB_MARKET_KEY') ? await карточкиВБ() : (пропущены.push('ВБ'), null);
  const площадки = await товарыПлощадок();
  const { товары } = площадки;
  пропущены.push(...площадки.пропущены);
  if (вб && !вб.length) throw new Error('ВБ: пришло 0 карточек — каталог не перезаписан');

  const продажи = await продажиПоШтрихкодам();
  const итог = собратьКаталог({ прошлый, вб, товары, продажи });
  if (прошлый.length >= 50 && итог.каталог.length < прошлый.length * ДОЛЯ_ОСТАТЬСЯ) {
    throw new Error(`каталог сжался бы с ${прошлый.length} до ${итог.каталог.length} позиций — `
      + 'похоже на сбой площадки, прежний каталог сохранён');
  }
  // колонки правее схемы — формулы книги; ширина записи ограничена схемой
  if (итог.каталог.some((р) => р.length !== ширина)) throw new Error('каталог: строка не по схеме');
  await сохранить(ЛИСТ, итог.каталог);
  await снимокСоСтроки(ШТРИХКОДЫ.лист, ШТРИХКОДЫ.отСтроки, ШТРИХКОДЫ.шапка.length, итог.штрихкоды);

  const поМП = [`ВБ ${вб ? вб.length : '-'}`,
    ...Object.entries(товары).map(([м, с]) => `${м} ${с.length}`)].join(', ');
  return `позиций ${итог.каталог.length} (новых ${итог.новых}, ушло ${итог.ушло}), `
       + `штрихкодов ${итог.штрихкоды.length}, главный 4620 у ${итог.главных4620}, товаров: ${поМП}`
       + (итог.дублей ? `, артикулов-дублей ${итог.дублей}` : '')
       + (пропущены.length ? `; из прошлого каталога: ${пропущены.join(', ')}` : '');
}
