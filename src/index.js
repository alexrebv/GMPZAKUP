/** Почему у задачи нет коннектора — чтобы в «Результате» стояло не загадочное «нет». */
const БЕЗ_КОННЕКТОРА = {
  'FBO остатки Мвидео': 'в API М.Видео нет схемы FBO, лист заливается выгрузкой из кабинета',
  'Заказы Мвидео FBO': 'в API М.Видео нет схемы FBO, лист заливается выгрузкой из кабинета',
};

async function выполнить(задача) {
  const обработчик = ОБРАБОТЧИКИ[задача.имя];
  if (!обработчик) {
    await отметитьЗапуск(задача, БЕЗ_КОННЕКТОРА[задача.имя] || 'нет коннектора, данные заливаются вручную');
    return;
  }
  const старт = Date.now();
  try {
    const результат = await обработчик(задача);
    const сек = ((Date.now() - старт) / 1000).toFixed(1);
    // период показываем только у задач, которые его используют: у остатков он смысла не несёт
    const подпись = задача.имя.startsWith('Заказы') ? описаниеПериода(задача) : '';
    const хвост = подпись ? `, ${подпись}` : '';
    await отметитьЗапуск(задача, `${результат}, ${сек} c${хвост}`);
    console.log(`[ok] ${задача.имя}: ${результат} (${сек} c)`);
  } catch (е) {
    await отметитьЗапуск(задача, `ОШИБКА: ${е.message}`.slice(0, 400));
    console.error(`[fail] ${задача.имя}: ${е.message}`);
  }
}

/**
 * Проходы нельзя пускать внахлёст. Задача может идти дольше минуты, а таймер
 * тикает всё равно: тогда «Последний запуск» ещё не записан, `пора()` снова
 * говорит «да», и та же задача уходит в работу вторым и третьим экземпляром.
 */
let идёт = false;

async function проход(принудительно = null) {
  const список = await задачи();
  const кЗапуску = принудительно
    ? список.filter((з) => з.имя === принудительно)
    // через стрелку, а не filter(пора): filter передаёт вторым доводом номер
    // элемента, и он вставал на место «сейчас» — каждый проход падал
    : список.filter((з) => пора(з));
  if (принудительно && !кЗапуску.length) {
    console.error(`задача «${принудительно}» не найдена в блоке задач на листе настроек`);
    process.exitCode = 1;
    return;
  }
  if (!кЗапуску.length) return;
  console.log(`к запуску: ${кЗапуску.map((з) => з.имя).join(', ')}`);
  for (const задача of кЗапуску) {
    await выполнить(задача);
  }
}

const аргументы = process.argv.slice(2);
const одинРаз = аргументы.includes('--once');
const позиция = аргументы.indexOf('--task');
const однаЗадача = позиция >= 0 ? аргументы[позиция + 1] : null;

/** Тик расписания: пропускаем, если прошлый проход ещё не закончился. */
function тик() {
  if (идёт) {
    console.log('прошлый проход ещё идёт, тик пропущен');
    return;
  }
  идёт = true;
  // проход роняет процесс только в разовых режимах: воркер должен пережить
  // временную недоступность Таблиц и попробовать снова через минуту
  проход()
    .catch((е) => console.error('сбой прохода:', е.message))
    .finally(() => { идёт = false; });
}

if (однаЗадача) {
  await проход(однаЗадача);
} else if (одинРаз) {
  await проход();
} else {
  console.log('сервис запущен, проверка расписания раз в минуту');
  тик();
  setInterval(тик, 60000);
}
