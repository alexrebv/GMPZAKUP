test('исчерпанный лимит объясняет себя, а не оставляет голое «HTTP 429»', async () => {
  // у токена «Базовый» лимит метода — один запрос в три часа, и выборка длиннее
  // одной страницы на нём не пройдёт никогда. Без объяснения человек пойдёт
  // искать поломку в коде
  await assert.rejects(собрать({ глубина: 7 }, { лимитИсчерпан: true }), (е) => {
    assert.match(е.message, /429/);
    assert.match(е.message, /ТРИ ЧАСА/);
    assert.match(е.message, /Базов/);
    return true;
  });
});

test('предел страниц соразмерен ёмкости листа', async () => {
  const { ПРЕДЕЛЫ_ЛЕНТЫ } = await import('../src/wb-ozon.js');
  // в лист влезает 50 000 строк (ПРЕДЕЛ в sheets.js). Предел страниц, за которым
  // лежит впятеро больше, означал бы час простоя воркера ради данных, которые
  // всё равно не запишутся
  const потолок = ПРЕДЕЛЫ_ЛЕНТЫ.пачка * ПРЕДЕЛЫ_ЛЕНТЫ.страниц;
  assert.ok(потолок <= 50000 * 2,
    `за пределом страниц ${потолок} заказов при ёмкости листа 50 000`);
  // и минута на страницу: дольше четверти часа держать расписание нельзя
  assert.ok(ПРЕДЕЛЫ_ЛЕНТЫ.страниц <= 15,
    `${ПРЕДЕЛЫ_ЛЕНТЫ.страниц} страниц по минуте — расписание встанет надолго`);
});

