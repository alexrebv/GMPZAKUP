test('тип отмены показывается только при статусе cancel', async () => {
  // на проданном заказе причина отмены — ложь, даже если метод её прислал
  const { строки } = await собрать({ глубина: 7 }, { всего: 10, отменаВсюду: true });
  const ст = СХЕМА.indexOf('Статус');
  const от = СХЕМА.indexOf('Тип отмены');
  for (const р of строки) {
    if (р[ст] !== 'cancel') {
      assert.equal(р[от], '-', `статус ${р[ст]}, а тип отмены ${р[от]}`);
    } else {
      assert.equal(р[от], 'app');
    }
  }
});

test('пустое поле «Тип отмены» не превращается в undefined', async () => {
  const { строки } = await собрать({ глубина: 7 }, { всего: 10 });
  const индекс = СХЕМА.indexOf('Тип отмены');
  for (const р of строки) {
    assert.notEqual(String(р[индекс]), 'undefined', 'в лист уехало слово undefined');
    assert.ok(р[индекс] === 'app' || р[индекс] === '-', `неожиданный тип отмены: ${р[индекс]}`);
  }
});

test('схема берётся из isMp: склад продавца — FBS, склад WB — FBO', async () => {
  const { строки } = await собрать({ глубина: 7 }, { всего: 4 });
  const индекс = СХЕМА.indexOf('Схема');
  assert.deepEqual(строки.map((р) => р[индекс]), ['FBS', 'FBO', 'FBS', 'FBO']);
});

test('недоступный справочник карточек не роняет выгрузку заказов', async () => {
  // справочник наполняет две колонки из восемнадцати и ходит по другому токену.
  // Заказы, статусы, цены и даты от него не зависят — терять их незачем
  const { строки, безСправочника } = await собрать(
    { глубина: 7 }, { всего: 4, карточкиОтказывают: true });
  assert.equal(строки.length, 4, 'заказы должны прийти и без справочника');
  assert.ok(безСправочника, 'о недоступном справочнике надо сказать вслух');
  const арт = СХЕМА.indexOf('Артикул продавца');
  const шк = СХЕМА.indexOf('Штрихкод');
  for (const р of строки) {
    assert.equal(р[арт], '-');
    assert.equal(р[шк], '');
  }
  // остальные колонки на месте
  assert.equal(строки[0][СХЕМА.indexOf('Валюта')], 'RUB');
  assert.equal(строки[0][СХЕМА.indexOf('Город доставки')], 'Санкт-Петербург');
});

test('артикул продавца и штрихкод подставляются из карточек', async () => {
  const { строки, безКарточки, безСправочника } = await собрать({ глубина: 7 }, { всего: 3 });
  const арт = СХЕМА.indexOf('Артикул продавца');
  const шк = СХЕМА.indexOf('Штрихкод');
  // карточки знают размеры 91663228 и 91663229, третий (…230) им неизвестен
  assert.equal(строки[0][арт], "'1970-01-29",
    'артикул-дата обязан уйти текстом, иначе Таблицы сделают из него дату');
  assert.equal(строки[0][шк], '4680000000000');
  assert.equal(строки[1][шк], "'0046800000001", 'ведущий ноль штрихкода обязан сохраниться');
  assert.equal(строки[2][арт], '-', 'размер без карточки должен давать прочерк');
  assert.equal(безКарточки, 1, `без карточки посчитано ${безКарточки}`);
  assert.equal(безСправочника, '', 'справочник был доступен — жаловаться не на что');
});
