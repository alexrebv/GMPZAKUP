test('сбой необязательной площадки не валит каталог, обязательной — валит', async () => {
  const есть = () => true;
  const ок = async () => [{ артикул: 'A' }];
  const сбой = async () => { throw new Error('М.Видео /v1/product/mapping/list: HTTP 400'); };
  const р = await товарыПлощадок({
    ОЗОН: { ключи: ['K'], загрузить: ок },
    Мвидео: { ключи: ['K'], загрузить: сбой, необязательна: true },
    Ламода: { ключи: ['K'], загрузить: async () => { throw new Error('не заполнено: LAMODA_SELLER_ID'); }, необязательна: true },
    Яндекс: { ключи: ['НЕТ'], загрузить: ок },
  }, (к) => к !== 'НЕТ');
  assert.deepEqual(Object.keys(р.товары), ['ОЗОН']);
  assert.match(р.пропущены.join(' | '), /Мвидео \(сбой: .*HTTP 400\)/);
  assert.match(р.пропущены.join(' | '), /Ламода \(нет LAMODA_SELLER_ID\)/);
  assert.ok(р.пропущены.includes('Яндекс'));
  await assert.rejects(товарыПлощадок({ ОЗОН: { ключи: ['K'], загрузить: сбой } }, есть), /HTTP 400/);
  // ноль товаров: у обязательной — ошибка, у необязательной — пропуск
  await assert.rejects(товарыПлощадок({ ОЗОН: { ключи: ['K'], загрузить: async () => [] } }, есть), /0 товаров/);
  const пусто = await товарыПлощадок({ Мвидео: { ключи: ['K'], загрузить: async () => [], необязательна: true } }, есть);
  assert.match(пусто.пропущены[0], /Мвидео \(сбой: .*0 товаров/);
});
