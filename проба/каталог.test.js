const без = (з) => String(з).replace(/^'/, '');
const ШАПКА = ['Штрихкод', 'Все штрихкоды', 'Кодов', 'Общий артикул', 'Размер', 'Наименование',
  'Бренд', 'Категория', 'Группа', 'Артикул ВБ', 'nmID', 'Артикул ОЗОН', 'SKU ОЗОН',
  'Артикул Яндекс', 'Артикул Ламода', 'SKU Ламода', 'Где заведён', 'Позиция'];

test('размеры-варианты узнаются, обычные — нет', () => {
  for (const р of ['30А', '30а', '30a', '30 АКЦИЯ', '40 Акция', '40акция', '30.', '34.', '30а(29)/180']) {
    assert.equal(вариантРазмера(р), true, р);
  }
  for (const р of ['30', '28', 'XL', '2XL', '40(38)', '36(34)/180', '0', 'UF', '26(28)']) {
    assert.equal(вариантРазмера(р), false, р);
  }
});

test('у обычного размера главный штрихкод — свой 4620, даже если он не первый', () => {
  assert.equal(главныйШтрихкод(['2041531990970', '4620251440620'], '28'), '4620251440620');
});

test('без 4620 главный — тот, по которому продажи, иначе первый', () => {
  const продажи = new Map([['2000000000002', 3]]);
  assert.equal(главныйШтрихкод(['2000000000001', '2000000000002'], '30', продажи), '2000000000002');
  assert.equal(главныйШтрихкод(['2000000000001', '2000000000002'], '30'), '2000000000001');
});

test('у варианта главный — первый штрихкод, а не 4620', () => {
  assert.equal(главныйШтрихкод(['2043819154449', '4620251444697'], '36 акция'), '2043819154449');
  assert.equal(главныйШтрихкод(['2048439700410', '4620251444666'], '28А'), '2048439700410');
});

test('у варианта продажи по другому штрихкоду перевешивают первый', () => {
  const продажи = new Map([['4620251444697', 5]]);
  assert.equal(главныйШтрихкод(['2043819154449', '4620251444697'], '30.', продажи), '4620251444697');
});

test('несколько 4620 — выигрывает тот, по которому продажи', () => {
  const продажи = new Map([['4620000000002', 1]]);
  assert.equal(главныйШтрихкод(['4620000000001', '4620000000002'], '30', продажи), '4620000000002');
});

