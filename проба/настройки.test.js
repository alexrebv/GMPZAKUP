import test from 'node:test';
import assert from 'node:assert/strict';
import '../src/tz.js';
import { задачаИзСтроки } from '../src/config.js';

/** Как книга хранит дату: днями от 30.12.1899. */
const серийно = (г, м, д) => (Date.UTC(г, м - 1, д) - Date.UTC(1899, 11, 30)) / 86400000;
const ПЕРВОЕ_АВГУСТА = серийно(2026, 8, 1);

/** Строка блока настроек: A имя, B вкл, C каждые, D глубина/«С даты», E «С даты», F последний, G результат. */
const строка = (о = {}) => [
  о.имя ?? 'Возвраты OZON FBS', о.вкл ?? 1, о.каждые ?? 5,
  о.d ?? '', о.e ?? '', о.f ?? '', о.g ?? '',
];

test('дата в колонке E читается как «С даты»', () => {
  const з = задачаИзСтроки(строка({ e: ПЕРВОЕ_АВГУСТА }), 41);
  assert.equal(з.сдаты, ПЕРВОЕ_АВГУСТА);
});

test('дата в колонке D тоже читается как «С даты»', () => {
  // в блоке возвратов обе колонки озаглавлены «С даты», и дата попадает в любую
  const з = задачаИзСтроки(строка({ d: ПЕРВОЕ_АВГУСТА }), 41);
  assert.equal(з.сдаты, ПЕРВОЕ_АВГУСТА);
  assert.equal(з.глубина, 0, 'дата не должна притвориться глубиной в 46235 дней');
});

test('дата в колонке D текстом читается так же', () => {
  const з = задачаИзСтроки(строка({ d: '01.08.2026' }), 41);
  assert.equal(з.сдаты, '01.08.2026');
  assert.equal(з.глубина, 0);
});

test('колонка E перевешивает колонку D', () => {
  const з = задачаИзСтроки(строка({ d: серийно(2026, 1, 1), e: ПЕРВОЕ_АВГУСТА }), 41);
  assert.equal(з.сдаты, ПЕРВОЕ_АВГУСТА);
});

test('глубина заказов не принимается за дату', () => {
  for (const глубина of [1, 7, 14, 31, 365]) {
    const з = задачаИзСтроки(строка({ имя: 'Заказы ОЗОН FBO', d: глубина, e: ПЕРВОЕ_АВГУСТА }), 20);
    assert.equal(з.глубина, глубина, `глубина ${глубина} съехала`);
    assert.equal(з.сдаты, ПЕРВОЕ_АВГУСТА);
  }
});

test('глубина текстом «31 д» по-прежнему разбирается', () => {
  const з = задачаИзСтроки(строка({ имя: 'Заказы ОЗОН FBO', d: '31 д' }), 20);
  assert.equal(з.глубина, 31);
  assert.equal(з.сдаты, '');
});

test('обе колонки пусты — периода нет', () => {
  const з = задачаИзСтроки(строка(), 41);
  assert.equal(з.сдаты, '');
  assert.equal(з.глубина, 0);
});

test('метка успеха переживает ошибку в «Результате»', () => {
  const отметка = серийно(2026, 9, 20) + 0.5;
  const свежий = задачаИзСтроки(строка({ f: отметка, g: 'возвратов 10, новых 2' }), 41);
  assert.ok(свежий.успешный, 'успешный прогон должен давать метку');

  const упавший = задачаИзСтроки(
    строка({ f: отметка, g: 'ОШИБКА: что-то | успех: 17.09.2026 09:00:00' }), 41);
  assert.ok(упавший.успешный, 'метка из текста ошибки потерялась');
  assert.equal(упавший.успешный.getDate(), 17);

  const безМетки = задачаИзСтроки(строка({ f: отметка, g: 'ОШИБКА: что-то' }), 41);
  assert.equal(безМетки.успешный, null);
});

// ─────────────────── границы блока задач ───────────────────

/**
 * Книга целиком не нужна: `задачи()` только читает блок, поэтому довольно
 * поддельного чтения. Пишет она в книгу из другого места — `отметитьЗапуск`.
 */
async function прочитать(строкиПоНомерам) {
  const { подставитьКлиент } = await import('../src/sheets.js');
  const { НАСТРОЙКИ } = await import('../src/schemas.js');
  const запрошено = [];
  подставитьКлиент({ spreadsheets: { values: {
    async get({ range }) {
      запрошено.push(range);
      const до = Number(range.match(/:G(\d+)$/)[1]);
      const значения = [];
      for (let с = НАСТРОЙКИ.задачиОт; с <= до; с += 1) {
        значения.push(строкиПоНомерам[с] || ['', '', '', '', '', '', '']);
      }
      // Таблицы не отдают пустой хвост — поддельное чтение тоже не должно
      while (значения.length && !значения[значения.length - 1].join('')) значения.pop();
      return { data: { values: значения } };
    },
  } } });
  const предупреждения = [];
  const было = console.warn;
  console.warn = (...а) => предупреждения.push(а.join(' '));
  try {
    const { задачи } = await import(`../src/config.js?${Math.random()}`);
    return { список: await задачи(), предупреждения, запрошено };
  } finally {
    console.warn = было;
  }
}

test('строка 61 входит в блок задач', async () => {
  // «WB заказы проверка» заведена в книге на 61-й строке. Проверка абсолютная,
  // а не «последняя строка блока»: иначе сужение блока обратно до 60 прошло бы
  // незамеченным, а задача просто перестала бы запускаться
  const { НАСТРОЙКИ } = await import('../src/schemas.js');
  assert.ok(НАСТРОЙКИ.задачиДо >= 61,
    `блок задач кончается на ${НАСТРОЙКИ.задачиДо}, а задача стоит в 61-й строке`);

  const { список } = await прочитать({ 61: строка({ имя: 'WB заказы проверка', вкл: 1 }) });
  assert.equal(список.length, 1, 'задача из 61-й строки не прочитана');
  assert.equal(список[0].строка, 61);
});

test('задача в последней строке блока запускается', async () => {
  const { НАСТРОЙКИ } = await import('../src/schemas.js');
  const последняя = НАСТРОЙКИ.задачиДо;
  const { список, предупреждения } = await прочитать({
    [последняя]: строка({ имя: 'WB заказы проверка', вкл: 1, каждые: 60 }),
  });
  assert.equal(список.length, 1, `задача из строки ${последняя} не прочитана`);
  assert.equal(список[0].имя, 'WB заказы проверка');
  assert.equal(список[0].строка, последняя);
  assert.deepEqual(предупреждения, []);
});

test('задача ниже блока не запускается, но и не молчит', async () => {
  const { НАСТРОЙКИ } = await import('../src/schemas.js');
  const ниже = НАСТРОЙКИ.задачиДо + 1;
  const { список, предупреждения } = await прочитать({
    [ниже]: строка({ имя: 'WB заказы проверка', вкл: 1 }),
  });
  assert.equal(список.length, 0, 'задача за концом блока работать не должна');
  assert.equal(предупреждения.length, 1, 'о невидимой задаче надо сказать вслух');
  assert.match(предупреждения[0], new RegExp(`строка ${ниже}`));
  assert.match(предупреждения[0], /ниже конца блока/);
  assert.match(предупреждения[0], /задачиДо/);
});

test('блок дочитывается с запасом — иначе строку ниже не увидеть', async () => {
  const { НАСТРОЙКИ } = await import('../src/schemas.js');
  const { запрошено } = await прочитать({ [НАСТРОЙКИ.задачиДо]: строка({ имя: 'FBS Возвраты' }) });
  const до = Number(запрошено[0].match(/:G(\d+)$/)[1]);
  assert.ok(до > НАСТРОЙКИ.задачиДо,
    `читаем до ${до} при конце блока ${НАСТРОЙКИ.задачиДо} — задачу ниже не заметим`);
});

test('включённая строка с чужим именем называется по номеру', async () => {
  const { список, предупреждения } = await прочитать({
    20: строка({ имя: 'Заказы ОЗОН ФБО', вкл: 1 }),   // опечатка: ФБО вместо FBO
  });
  assert.equal(список.length, 0);
  assert.equal(предупреждения.length, 1);
  assert.match(предупреждения[0], /строка 20/);
  assert.match(предупреждения[0], /такой задачи нет/);
});
