import test from 'node:test';
import assert from 'node:assert/strict';
import '../src/tz.js';
import { сохранить } from '../src/sheets.js';
import { СХЕМЫ } from '../src/schemas.js';
import { поддельнаяКнига, серийно } from './поддельная-книга.js';

const ЛИСТ = 'Возвраты OZON';
const СХЕМА = СХЕМЫ[ЛИСТ];

const возврат = (н, артикул, статус = 'В пути') => [
  `R${н}`, `П-${н}`, `З-${н}`, 'Fbs', артикул, `110052620${н}`, `Товар ${н}`, 1, 3318,
  'причина', 'FullReturn', статус, '02.09.2026 10:00:00', '01.09.2026 10:00:00',
  'СЦ', `ii527${н}`, '23.09.2026 12:00:00'];

test('шапка проставляется в пустую первую строку', async () => {
  const { книга } = поддельнаяКнига({ [ЛИСТ]: [] });
  const итог = await сохранить(ЛИСТ, [возврат(1, "'025-12-31")]);
  assert.deepEqual(книга.get(ЛИСТ)[0], СХЕМА);
  assert.match(итог.заметка, /шапка проставлена/);
});

test('занятые клетки шапки не трогаем, пустые дозаполняем', async () => {
  const своя = ['МОЙ ЗАГОЛОВОК', '', '', 'СХЕМА ПО-СВОЕМУ'];
  const { книга } = поддельнаяКнига({ [ЛИСТ]: [своя] });
  await сохранить(ЛИСТ, [возврат(1, "'025-12-31")]);
  const шапка = книга.get(ЛИСТ)[0];
  assert.equal(шапка[0], 'МОЙ ЗАГОЛОВОК', 'чужой заголовок затёрт');
  assert.equal(шапка[3], 'СХЕМА ПО-СВОЕМУ', 'чужой заголовок затёрт');
  assert.equal(шапка[1], СХЕМА[1], 'пустая клетка не заполнена');
  assert.equal(шапка[16], СХЕМА[16], 'хвост шапки не заполнен');
});

test('артикул-дата ложится текстом, а не датой', async () => {
  const { книга } = поддельнаяКнига({ [ЛИСТ]: [СХЕМА] });
  await сохранить(ЛИСТ, [возврат(1, "'025-12-31")]);
  assert.equal(книга.get(ЛИСТ)[1][4], '025-12-31');
});

test('испорченный ранее артикул чинится сам', async () => {
  const испорчено = возврат(1, серийно(2025, 12, 31));
  const { книга } = поддельнаяКнига({ [ЛИСТ]: [СХЕМА, испорчено] });
  const итог = await сохранить(ЛИСТ, [возврат(1, "'025-12-31")]);
  assert.equal(итог.изменено, 1, 'строка не признана изменившейся');
  assert.equal(книга.get(ЛИСТ)[1][4], '025-12-31');
});

test('артикул с ведущим нулём чинится, хотя как число он равен книжному', async () => {
  // книга хранит 12345, мы шлём «0012345»: числовое приведение сочло бы их равными
  const испорчено = возврат(1, 12345);
  const { книга } = поддельнаяКнига({ [ЛИСТ]: [СХЕМА, испорчено] });
  const итог = await сохранить(ЛИСТ, [возврат(1, "'0012345")]);
  assert.equal(итог.изменено, 1, 'ведущий ноль не восстановлен');
  assert.equal(книга.get(ЛИСТ)[1][4], '0012345');
});

test('когда ничего не изменилось — ни одной записи', async () => {
  const { книга, записи } = поддельнаяКнига({ [ЛИСТ]: [СХЕМА] });
  await сохранить(ЛИСТ, [возврат(1, "'025-12-31")]);
  записи.length = 0;
  const итог = await сохранить(ЛИСТ, [возврат(1, "'025-12-31")]);
  assert.equal(итог.новых, 0);
  assert.equal(итог.изменено, 0);
  assert.equal(записи.length, 0, 'лист переписан впустую');
  assert.equal(книга.get(ЛИСТ)[1][4], '025-12-31');
});

test('в книгу не уходит ничего, прочитанного ИЗ книги', async () => {
  // пятьсот строк, у каждой второй меняется статус: это 250 несмежных кусков
  // правок, больше прежнего порога в 200, и раньше включалась ветка
  // «переписать блок целиком» — неизменившиеся строки уезжали обратно в книгу
  // уже без пометки «текст» и снова становились датами
  const было = [СХЕМА];
  for (let i = 0; i < 500; i += 1) было.push(возврат(i, '025-12-31'));  // как хранит книга
  const { книга, записи } = поддельнаяКнига({ [ЛИСТ]: было });
  const свежие = Array.from({ length: 500 }, (_, i) =>
    возврат(i, "'025-12-31", i % 2 ? 'Вручён' : 'В пути'));

  await сохранить(ЛИСТ, свежие);

  const артикулы = книга.get(ЛИСТ).slice(1).map((р) => р[4]);
  const сломанные = артикулы.filter((а) => typeof а !== 'string');
  assert.equal(сломанные.length, 0,
    `${сломанные.length} артикулов снова стали датами при обратной записи`);
  // и ни одна запись не должна содержать значение, взятое из книги
  for (const з of записи) {
    for (const р of з.values) {
      if (р === СХЕМА) continue;
      assert.ok(р[4] === undefined || String(р[4]).startsWith("'") || р[4] === СХЕМА[4],
        `в книгу ушёл неразмеченный артикул ${JSON.stringify(р[4])}`);
    }
  }
});

test('девятнадцатизначные srid не схлопываются в один ключ', async () => {
  // Number() держит пятнадцать значащих цифр. Раньше ключ считался числом, и пять
  // разных заказов сводились к одному: четыре строки молча исчезали, а на следующем
  // прогоне новый заказ находил по тому же ключу чужую строку и затирал её
  const ЛИСТ_Л = 'WB заказы проверка';
  const схема = СХЕМЫ[ЛИСТ_Л];
  const { книга } = поддельнаяКнига({ [ЛИСТ_Л]: [schemaШапка(схема)] });

  const строка = (хвост) => {
    const р = new Array(схема.length).fill('-');
    р[0] = `'751343203471363294${хвост}`;         // ровно 19 цифр, без точек
    р[схема.length - 1] = '01.10.2026 12:00:00';
    return р;
  };
  const строки = [3, 4, 5, 6, 7].map(строка);
  const итог = await сохранить(ЛИСТ_Л, строки);

  assert.equal(итог.новых, 5, `записано новых ${итог.новых} вместо пяти`);
  const вЛисте = (книга.get(ЛИСТ_Л) || []).slice(1).filter((р) => (р || []).length);
  assert.equal(вЛисте.length, 5, `в листе ${вЛисте.length} строк вместо пяти`);
  const srid = new Set(вЛисте.map((р) => String(р[0])));
  assert.equal(srid.size, 5, `разных srid в листе ${srid.size} — ключи схлопнулись`);

  // второй прогон теми же строками не должен ни добавить, ни затереть
  const повтор = await сохранить(ЛИСТ_Л, строки);
  assert.equal(повтор.новых, 0, `повторный прогон добавил ${повтор.новых} строк`);
  assert.equal(повтор.изменено, 0, `повторный прогон переписал ${повтор.изменено} строк`);
});

function schemaШапка(схема) { return схема.map((и) => и); }
