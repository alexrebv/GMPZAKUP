/**
 * Проверяет, что документация не врёт о коде.
 *
 * Раньше здесь сверялись номера строк. Это оказалось хуже, чем ничего: номер
 * устаревает от любой вставки, а проверка «строка существует и не пуста»
 * пропускает съехавшую ссылку — документ продолжает выглядеть точным, указывая
 * не туда. Поймали это дважды, оба раза задним числом.
 *
 * Теперь номеров в документации нет вовсе, а сверяется то, что устареть молча
 * не может: названы ли существующие файлы, живы ли упомянутые адреса методов,
 * существуют ли названные константы, переменные окружения и листы книги.
 */
import { readFile, readdir } from 'node:fs/promises';
import path from 'node:path';

const КОРЕНЬ = path.resolve(import.meta.dirname, '..');

/** Имена, которые в коде искать незачем: это значения данных или общие слова. */
const НЕ_КОД = new Set([
  'RUB', 'FBO', 'FBS', 'FBY', 'B2B', 'B2C', 'WB', 'OZON', 'ID', 'SKU', 'HTTP',
  'JSON', 'API', 'RPC', 'REST', 'CSV', 'UTC', 'ПВЗ', 'ШК', 'DNS', 'CI', 'OK',
  'NMID', 'SRID', 'ПАГИНАЦИЯ', 'ОШИБКА', 'ВНИМАНИЕ', 'НЕ', 'ФИЛЬТР', 'ПРИМЕНЁН',
  'СПРАВОЧНИК', 'КАРТОЧЕК', 'НЕДОСТУПЕН',
]);

/**
 * Имя целиком, а не как подстрока.
 *
 * Простое includes() ловило не всё: приписав к имени константы хвост, старое имя
 * всё ещё «находится» внутри нового, и расхождение проходит незамеченным.
 * \b тут не годится: кириллица для него не словесный символ.
 */
const ГРАНИЦА = '[A-Za-zА-Яа-яЁё0-9_]';
function естьЦеликом(имя, текст) {
  const э = имя.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`(?<!${ГРАНИЦА})${э}(?!${ГРАНИЦА})`, 'u').test(текст);
}

/**
 * Адрес метода — отдельный случай. Слева от него стоит имя хоста, поэтому
 * граница слева не годится: в `…lamoda.ru/rpc` перед путём стоит буква.
 * Справа путь законно продолжается через дробь (`/api/v3/stocks/${склад.id}`),
 * так что запрещаем только дописанный хвост: order-feed против order-feed-v2.
 */
function естьПуть(путь, текст) {
  for (let i = текст.indexOf(путь); i >= 0; i = текст.indexOf(путь, i + 1)) {
    const следом = текст[i + путь.length] || '';
    if (!/[A-Za-z0-9_-]/.test(следом)) return true;
  }
  return false;
}

async function прочитать(каталог, расширения) {
  const итог = new Map();
  let имена;
  try {
    имена = await readdir(path.join(КОРЕНЬ, каталог));
  } catch {
    return итог;
  }
  for (const и of имена) {
    if (!расширения.some((р) => и.endsWith(р))) continue;
    итог.set(`${каталог}/${и}`, await readFile(path.join(КОРЕНЬ, каталог, и), 'utf8'));
  }
  return итог;
}

/** Для проверки «существует ли файл» годятся все исходники. */
const исходники = new Map([
  ...(await прочитать('src', ['.js'])),
  ...(await прочитать('scripts', ['.mjs'])),
  ...(await прочитать('проба', ['.js'])),
]);

/**
 * А вот имена и адреса сверяем ТОЛЬКО с кодом сервиса.
 *
 * Пробы держат поддельные серверы с теми же адресами, а служебные скрипты —
 * пояснения с именами констант. И то и другое маскирует расхождение: убери
 * константу из сервиса, и она «найдётся» в чужом комментарии. Этот скрипт
 * однажды нашёл имя в собственном тексте и промолчал.
 */
const кодСервиса = [...(await прочитать('src', ['.js'])).values()].join('\n');
const пример = await readFile(path.join(КОРЕНЬ, '.env.example'), 'utf8').catch(() => '');

/**
 * ves-kod.md не проверяем: это сгенерированный снимок самого кода, а не рассказ
 * о нём. Сверять его с кодом нечего, зато примеры из комментариев этого скрипта
 * попали бы туда и подняли ложную тревогу на себя же.
 */
const документы = new Map(
  [...(await прочитать('docs', ['.md'])),
    ['README.md', await readFile(path.join(КОРЕНЬ, 'README.md'), 'utf8')]]
    .filter(([имя]) => !имя.endsWith('ves-kod.md')),
);

/** Числа блока настроек берём из кода: в прозе они устаревают молча. */
const настройки = Object.fromEntries(
  [...(исходники.get('src/schemas.js') || '').matchAll(/(задачиОт|задачиДо|параметрыОт|параметрыДо):\s*(\d+)/g)]
    .map(([, к, з]) => [к, Number(з)]),
);
for (const к of ['задачиОт', 'задачиДо', 'параметрыОт', 'параметрыДо']) {
  if (!настройки[к]) {
    console.log(`  src/schemas.js: не нашёл НАСТРОЙКИ.${к} — проверка диапазонов не работает`);
    process.exitCode = 1;
  }
}

let плохо = 0;
let проверено = 0;
const жалоба = (док, что) => { console.log(`  ${док}: ${что}`); плохо += 1; };

for (const [док, текст] of документы) {
  // ── 1. названные файлы существуют
  for (const [, имя] of текст.matchAll(/`([\wа-яё-]+\.(?:js|mjs))`/giu)) {
    проверено += 1;
    if (![...исходники.keys()].some((к) => k_имя(к) === имя)) {
      жалоба(док, `файла \`${имя}\` нет`);
    }
  }

  // ── 2. адреса методов живы
  for (const [, путь] of текст.matchAll(/`(?:GET|POST) (\/[\w{}/.-]+)/g)) {
    проверено += 1;
    // в коде путь часто собран из куска и подстановки: ищем первый устойчивый отрезок
    const отрезок = путь.split(/[{]/)[0].replace(/\/$/, '');
    if (отрезок.length > 3 && !естьПуть(отрезок, кодСервиса)) {
      жалоба(док, `адреса \`${путь}\` в коде нет (искал «${отрезок}»)`);
    }
  }

  // ── 3. названные константы и переменные окружения существуют
  for (const [, имя] of текст.matchAll(/`([A-ZА-ЯЁ][A-ZА-ЯЁ0-9_]{2,})`/gu)) {
    if (НЕ_КОД.has(имя)) continue;
    проверено += 1;
    if (!естьЦеликом(имя, кодСервиса) && !естьЦеликом(имя, пример)) {
      жалоба(док, `\`${имя}\` не найдено ни в коде, ни в .env.example`);
    }
  }

  // ── 4. имена вида задачиДо и подставитьКлиент: заглавная буква внутри слова
  // в обычном тексте не встречается, поэтому это надёжный признак кода
  // `имяФункции()` со скобками — такая же ссылка на код, как и без них
  for (const [, имя] of текст.matchAll(/`([а-яё]{1,}[А-ЯЁA-Z][А-Яа-яЁёA-Za-z]*)(?:\(\))?`/gu)) {
    проверено += 1;
    if (!естьЦеликом(имя, кодСервиса)) {
      жалоба(док, `\`${имя}\` в коде сервиса не найдено`);
    }
  }

  /**
   * ── 5. диапазоны блока настроек в прозе совпадают с НАСТРОЙКАМИ.
   *
   * Именно на этом и погорели: «задачиДо» стало 61, а четыре места в документах
   * продолжали говорить «строки 15–60» и «A15:G60». Это та самая инструкция,
   * по которой задачу вписывают туда, где сервис её не видит.
   */
  for (const [целиком, до] of текст.matchAll(/`A15:G(\d+)`/g)) {
    проверено += 1;
    if (Number(до) !== настройки.задачиДо) {
      жалоба(док, `${целиком}: блок задач кончается на ${настройки.задачиДо}`);
    }
  }
  for (const [целиком, до] of текст.matchAll(/`A3:B(\d+)`/g)) {
    проверено += 1;
    if (Number(до) !== настройки.параметрыДо) {
      жалоба(док, `${целиком}: параметры кончаются на ${настройки.параметрыДо}`);
    }
  }
  for (const [целиком, от, до] of текст.matchAll(/строк[иауе]?\s+(\d+)\s*[–—-]\s*(\d+)/gu)) {
    if (Number(от) !== настройки.задачиОт) continue;   // это не про блок задач
    проверено += 1;
    if (Number(до) !== настройки.задачиДо) {
      жалоба(док, `«${целиком}»: блок задач — ${настройки.задачиОт}–${настройки.задачиДо}`);
    }
  }

  // ── 6. имена листов книги совпадают с схемами посимвольно
  const схемы = исходники.get('src/schemas.js') || '';
  for (const [, лист] of текст.matchAll(/«([A-Za-zА-Яа-яЁё][^»]{3,40})»/gu)) {
    if (!/остатки|Заказы|Возвраты|заказы проверка|Настройки/.test(лист)) continue;
    проверено += 1;
    if (!схемы.includes(лист)) {   // имя листа — строка целиком, подстрокой не спутать
      жалоба(док, `листа «${лист}» нет в schemas.js`);
    }
  }
}

function k_имя(ключ) { return ключ.slice(ключ.lastIndexOf('/') + 1); }

console.log(`проверок ${проверено}, расхождений ${плохо}`);
if (плохо) process.exitCode = 1;
